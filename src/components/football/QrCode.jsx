import { useEffect, useState } from 'react'
import QRCode from 'qrcode'

/** QR code rendered locally as SVG (no network). */
export default function QrCode({ text, size = 280, dark = '#000080', light = '#ffffff', className = '' }) {
  const [svg, setSvg] = useState('')

  useEffect(() => {
    let alive = true
    if (!text) return
    QRCode.toString(text, { type: 'svg', margin: 1, errorCorrectionLevel: 'M', color: { dark, light } })
      .then((s) => alive && setSvg(s))
      .catch(() => alive && setSvg(''))
    return () => {
      alive = false
    }
  }, [text, dark, light])

  return (
    <div
      className={`overflow-hidden rounded-2xl bg-white [&>svg]:h-full [&>svg]:w-full ${className}`}
      style={{ width: size, height: size }}
      // generated by the qrcode library from our own text — safe to inject
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  )
}

/** Wi-Fi join string understood by iPhone & Android cameras. */
export function wifiQrText({ ssid, password, security = 'WPA' }) {
  const esc = (s) => String(s).replace(/([\\;,:"])/g, '\\$1')
  return `WIFI:T:${security};S:${esc(ssid)};P:${esc(password)};;`
}
